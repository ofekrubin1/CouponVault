// Stores every known brand's site icon with the app (public/brands/icons), for the brands that have no logo of
// their own in public/brands. Logos served by the app itself can be drawn into a shared coupon image; Google's
// icon service doesn't allow that (no CORS), so without a local copy the shared image had no logo.
// Run again after adding brands: node scripts/fetch-brand-icons.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { BRANDS, OWN_LOGOS } from '../src/domain/brandCatalog.js';

const DIR = 'public/brands/icons';
const MIN = 24; // same as the app: Google answers an unknown site with a tiny generic globe; skip those
const safe = (domain) => domain.replace(/[^a-z0-9.-]+/gi, '_');

/** Width of a PNG or JPEG from its header (null if it's neither). */
function imageWidth(buf) {
  if (buf.length > 24 && buf.readUInt32BE(0) === 0x89504e47) return { ext: 'png', w: buf.readUInt32BE(16) };
  if (buf.length > 4 && buf[0] === 0xff && buf[1] === 0xd8) {
    for (let i = 2; i < buf.length - 9; ) {
      if (buf[i] !== 0xff) return null;
      const marker = buf[i + 1];
      if (marker >= 0xc0 && marker <= 0xc3) return { ext: 'jpg', w: buf.readUInt16BE(i + 7) }; // start of frame
      i += 2 + buf.readUInt16BE(i + 2);
    }
  }
  return null;
}

mkdirSync(DIR, { recursive: true });
const saved = {};
const skipped = [];
for (const [domain] of BRANDS) {
  if (OWN_LOGOS[domain]) continue;
  try {
    const res = await fetch(`https://www.google.com/s2/favicons?domain=${encodeURIComponent(domain)}&sz=128`);
    const buf = Buffer.from(await res.arrayBuffer());
    const img = imageWidth(buf);
    if (!res.ok || !img || img.w < MIN) {
      skipped.push(`${domain} (${img ? `${img.w}px` : res.headers.get('content-type')})`);
      continue;
    }
    const file = `${safe(domain)}.${img.ext}`;
    writeFileSync(`${DIR}/${file}`, buf);
    saved[domain] = file;
  } catch (e) {
    skipped.push(`${domain} (${e.message})`);
  }
}

const list = Object.keys(saved)
  .sort()
  .map((d) => `  '${d}': '${saved[d]}',`)
  .join('\n');
writeFileSync(
  'src/domain/brandIcons.js',
  `// Generated by scripts/fetch-brand-icons.mjs: brands whose site icon is stored with the app (public/brands/icons).\nexport const LOCAL_ICONS = {\n${list}\n};\n`,
);
console.log(`saved ${Object.keys(saved).length} icons`);
if (skipped.length) console.log(`no usable icon for: ${skipped.join(', ')}`);
